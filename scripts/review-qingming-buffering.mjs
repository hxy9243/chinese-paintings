import {chromium} from "../artworks/qingming/node_modules/playwright/index.mjs";
import {preview} from "../artworks/qingming/node_modules/vite/dist/node/index.js";
import fs from "node:fs";import path from "node:path";
const out=process.env.REVIEW_DIR??"docs/reviews/2026-10-21-river-bend";fs.mkdirSync(out,{recursive:true});
const server=await preview({root:"artworks/qingming",preview:{host:"127.0.0.1",port:4185,strictPort:true}});
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,args:["--no-sandbox","--disable-dev-shm-usage","--use-angle=swiftshader","--enable-unsafe-swiftshader"]});
const errors=[];
try{
 const page=await browser.newPage({viewport:{width:1500,height:1000},reducedMotion:"reduce"});
 const fonts=process.env.QINGMING_QA_FONTS;
 const css=fs.readFileSync(path.join(fonts,"400.css"),"utf8").replaceAll("./files/","https://qingming-fonts.test/");
 await page.route("https://fonts.googleapis.com/**",r=>r.fulfill({contentType:"text/css",body:css}));
 await page.route("https://qingming-fonts.test/**",r=>r.fulfill({contentType:"font/woff2",headers:{"access-control-allow-origin":"*"},body:fs.readFileSync(path.join(fonts,"files",path.basename(new URL(r.request().url()).pathname)))}));
 page.on("pageerror",e=>errors.push(e.message));page.on("console",m=>{if(m.type()==="error")errors.push(m.text());});
 await page.goto("http://127.0.0.1:4185/");
 const canvas=page.locator(".study-canvas canvas");
 await page.waitForFunction(()=>document.querySelector(".study-canvas canvas")?.dataset.quality==="refined",undefined,{timeout:120000});
 await page.waitForTimeout(600);
 const before=await canvas.evaluate(c=>({frames:Number(c.dataset.frames),width:c.width}));
 await page.waitForTimeout(300);
 const idle=await canvas.evaluate(c=>Number(c.dataset.frames));
 if(idle!==before.frames)throw Error("Paused scene still draws idle frames");
 const bounds=await canvas.boundingBox();
 await page.mouse.move(bounds.x+bounds.width*.5,bounds.y+bounds.height*.5);await page.mouse.down();
 await page.mouse.move(bounds.x+bounds.width*.6,bounds.y+bounds.height*.54,{steps:8});
 await page.waitForFunction(()=>document.querySelector(".study-canvas canvas")?.dataset.quality==="preview");
 const dragging=await canvas.evaluate(c=>({quality:c.dataset.quality,width:c.width}));
 await page.locator(".study-stage").screenshot({path:out+"/drag-preview.jpg",type:"jpeg",quality:90});
 if(dragging.width>=before.width)throw Error("Drag buffer did not reduce resolution");
 await page.mouse.up();
 await page.waitForFunction(()=>document.querySelector(".study-canvas canvas")?.dataset.quality==="refined");
 await page.waitForTimeout(400);
 const refined=await canvas.evaluate(c=>({quality:c.dataset.quality,width:c.width,frames:Number(c.dataset.frames)}));
 if(refined.width!==before.width)throw Error("Refined buffer did not restore resolution");
 await page.locator(".study-stage").screenshot({path:out+"/settled-refined.jpg",type:"jpeg",quality:94});
 await page.getByRole("button",{name:"Explore the scroll"}).click();
 await page.getByRole("button",{name:"River bend",exact:true}).click();
 await page.waitForFunction(()=>document.querySelector(".study-canvas canvas")?.dataset.quality==="refined");
 await page.waitForTimeout(400);
 const traveled=await canvas.evaluate(c=>Number(c.dataset.frames));
 if(traveled<=refined.frames)throw Error("Travel did not invalidate the paused view");
 await page.getByRole("button",{name:"Resume life"}).click();
 const runningStart=await canvas.evaluate(c=>Number(c.dataset.frames));await page.waitForTimeout(400);
 const runningEnd=await canvas.evaluate(c=>Number(c.dataset.frames));
 if(runningEnd<=runningStart)throw Error("Resume did not restart rendering");
 const report={errors,before,idle,dragging,refined,traveled,runningStart,runningEnd};
 fs.writeFileSync(out+"/buffering.json",JSON.stringify(report,null,2)+"\n");console.log(JSON.stringify(report));
 if(errors.length)process.exitCode=1;
}finally{await browser.close();await new Promise(r=>server.httpServer.close(r));}
